import assert from "node:assert/strict";
import test from "node:test";

import { issueSourceRevisionSha256 } from "../../dist/repair/issue-source-guard.js";

const issue = {
  number: 244,
  state: "open",
  locked: false,
  title: "Add reviewed behavior",
  body: "Implement the narrow reviewed request.",
  labels: [{ name: "enhancement" }],
};

test("source issue revision ignores ClawSweeper comments but tracks human edits", () => {
  const humanComment = {
    id: 2,
    user: { login: "maintainer" },
    body: "keep this narrow",
    updated_at: "2026-06-11T10:01:00Z",
  };
  const botAliases = [
    "clawsweeper",
    "clawsweeper[bot]",
    "openclaw-clawsweeper",
    "openclaw-clawsweeper[bot]",
    "ayobamih-clawsweeper",
    "ayobamih-clawsweeper[bot]",
  ];

  for (const login of botAliases) {
    const botComment = {
      id: 1,
      user: { login },
      body: "review v1",
      updated_at: "2026-06-11T10:00:00Z",
    };
    const revision = issueSourceRevisionSha256(issue, [botComment, humanComment]);

    assert.equal(
      issueSourceRevisionSha256(issue, [
        { ...botComment, body: "review v2", updated_at: "2026-06-11T10:02:00Z" },
        humanComment,
      ]),
      revision,
      `expected ${login} comments to be excluded from the source revision`,
    );
  }

  const revision = issueSourceRevisionSha256(issue, [humanComment]);
  assert.notEqual(
    issueSourceRevisionSha256(issue, [
      { ...humanComment, body: "expanded request", updated_at: "2026-06-11T10:03:00Z" },
    ]),
    revision,
  );
});

test("source issue revision ignores automation labels but tracks human labels", () => {
  const revision = issueSourceRevisionSha256(issue, []);

  assert.equal(
    issueSourceRevisionSha256(
      {
        ...issue,
        labels: [
          ...issue.labels,
          { name: "status: ⏳ waiting on author" },
          { name: "rating: 🧂 unranked krab" },
          { name: "proof: sufficient" },
          { name: "merge-risk: 🚨 automation" },
          { name: "impact:message-loss" },
          { name: "issue-rating: 🦪 silver shellfish" },
          { name: "P1" },
          { name: "maturity:stable" },
          { name: "feature: ✨ showcase" },
          { name: "good first issue" },
          { name: "mantis: telegram-visible-proof" },
          { name: "proof: telegram-e2e" },
          { name: "triage: needs-real-behavior-proof" },
          { name: "clawsweeper:reviewed" },
          { name: "clawsweeper:autogenerated" },
          { name: "no-stale" },
          { name: "stale" },
        ],
      },
      [],
    ),
    revision,
  );
  assert.notEqual(
    issueSourceRevisionSha256(
      { ...issue, labels: [...issue.labels, { name: "needs-design" }] },
      [],
    ),
    revision,
  );
  assert.notEqual(
    issueSourceRevisionSha256(
      { ...issue, labels: [...issue.labels, { name: "clawsweeper:manual-only" }] },
      [],
    ),
    revision,
  );
  assert.notEqual(
    issueSourceRevisionSha256(
      { ...issue, labels: [...issue.labels, { name: "clawsweeper:bulk-filed" }] },
      [],
    ),
    revision,
  );
  assert.notEqual(
    issueSourceRevisionSha256(
      { ...issue, labels: [...issue.labels, { name: "release-blocker" }] },
      [],
    ),
    revision,
  );
});
